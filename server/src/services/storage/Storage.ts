import { createReadStream } from "node:fs";
import { mkdir, rm, stat, writeFile } from "node:fs/promises";
import path from "node:path";
import type { Readable } from "node:stream";

/** File storage. Local disk in development; S3-compatible EU storage in production (Phase 5). */
export interface Storage {
  put(key: string, data: Buffer, contentType: string): Promise<void>;
  get(key: string): Promise<{ stream: Readable; size: number }>;
  remove(key: string): Promise<void>;
}

export class LocalDiskStorage implements Storage {
  constructor(private readonly root: string) {}

  private resolve(key: string): string {
    // Keys are generated by the server (no user input), but never allow escaping the root.
    const full = path.resolve(this.root, key);
    if (!full.startsWith(path.resolve(this.root) + path.sep)) throw new Error("Invalid storage key");
    return full;
  }

  async put(key: string, data: Buffer): Promise<void> {
    const file = this.resolve(key);
    await mkdir(path.dirname(file), { recursive: true });
    await writeFile(file, data);
  }

  async get(key: string) {
    const file = this.resolve(key);
    const info = await stat(file);
    return { stream: createReadStream(file), size: info.size };
  }

  async remove(key: string): Promise<void> {
    await rm(this.resolve(key), { force: true });
  }
}
